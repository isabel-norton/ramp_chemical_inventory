import os
from contextlib import contextmanager
from datetime import date

import pandas as pd
import psycopg2
import streamlit as st

st.set_page_config(page_title="Lab Chemical Inventory", page_icon="🧪", layout="centered")

UNIT_GROUPS = {
    "mg": ("mass", 0.001), "g": ("mass", 1), "kg": ("mass", 1000),
    "µL": ("volume", 0.001), "mL": ("volume", 1), "L": ("volume", 1000),
    "items": ("count", 1),
    "gal": ("volume", 3785.411784),
}


def db_url():
    try:
        return st.secrets["SUPABASE_DB_URL"]
    except (KeyError, FileNotFoundError):
        return os.environ.get("SUPABASE_DB_URL", "")


@contextmanager
def connection():
    conn = psycopg2.connect(db_url(), sslmode="require", connect_timeout=12)
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def run(query, params=(), fetch=False):
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute(query, params)
            return cur.fetchall() if fetch else None


def init_database():
    run("""
        CREATE TABLE IF NOT EXISTS chemicals (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            identifier TEXT NOT NULL DEFAULT '',
            starting_amount DOUBLE PRECISION NOT NULL CHECK (starting_amount >= 0),
            unit TEXT NOT NULL,
            active BOOLEAN NOT NULL DEFAULT TRUE,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        );
        CREATE TABLE IF NOT EXISTS usage_logs (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            chemical_id BIGINT NOT NULL REFERENCES chemicals(id) ON DELETE RESTRICT,
            used_on DATE NOT NULL,
            amount DOUBLE PRECISION NOT NULL CHECK (amount > 0),
            unit TEXT NOT NULL,
            note TEXT NOT NULL DEFAULT '',
            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        );
        CREATE INDEX IF NOT EXISTS usage_logs_chemical_id_idx ON usage_logs(chemical_id);
    """)


def all_chemicals():
    return run("SELECT id, name, identifier, starting_amount, unit, active FROM chemicals ORDER BY lower(name), id", fetch=True)


def all_logs():
    return run("""SELECT l.id, l.chemical_id, c.name, l.used_on, l.amount, l.unit, l.note
                  FROM usage_logs l JOIN chemicals c ON c.id=l.chemical_id
                  ORDER BY l.used_on DESC, l.id DESC""", fetch=True)


def to_base(amount, unit):
    return float(amount) * UNIT_GROUPS[unit][1]


def remaining(chemical, logs):
    cid, _, _, starting, unit, _ = chemical
    used = sum(to_base(row[4], row[5]) for row in logs if row[1] == cid)
    return (to_base(starting, unit) - used) / UNIT_GROUPS[unit][1]


def label(chemical):
    cid, name, identifier, _, _, _ = chemical
    return f"{name} ({identifier}) · #{cid}" if identifier else f"{name} · #{cid}"


st.title("🧪 Lab Chemical Inventory")
st.caption("Shared chemical stock and usage records • Stored in Supabase")

if not db_url():
    st.error("Missing SUPABASE_DB_URL. Add it to Streamlit Secrets before using this app.")
    st.stop()

try:
    init_database()
    chemicals = all_chemicals()
    logs = all_logs()
except Exception as exc:
    st.error("Could not connect to Supabase. Check the connection string, database password, and pooler settings.")
    with st.expander("Technical details"):
        st.code(str(exc))
    st.stop()

active = [c for c in chemicals if c[5]]
by_id = {c[0]: c for c in chemicals}

log_tab, inventory_tab, history_tab, manage_tab = st.tabs(["Log usage", "Inventory", "History", "Manage"])

with log_tab:
    st.subheader("Record chemical use")
    if not active:
        st.info("Add a chemical under Manage to get started.")
    else:
        # Keep widgets outside a form so Streamlit updates button state as the user types.
        selected = st.selectbox("Chemical *", active, format_func=label)
        unit = selected[4]
        group = UNIT_GROUPS[unit][0]
        choices = [u for u, (g, _) in UNIT_GROUPS.items() if g == group]
        amount = st.number_input("Amount used *", min_value=0.0, value=0.0, step=0.1, format="%.4f")
        used_unit = st.selectbox("Unit *", choices, index=choices.index(unit))
        used_on = st.date_input("Date used *", value=date.today())
        note = st.text_input("Your name *", placeholder="Enter your name")
        valid = bool(selected and used_unit and used_on and amount > 0 and note.strip())
        submitted = st.button("Save usage", type="primary", use_container_width=True, disabled=not valid)
        st.caption("* Required fields. Enter an amount greater than zero and your name to enable Save usage.")
        current = remaining(selected, logs)
        st.caption(f"Current stock: {current:,.4f} {unit}")
        if submitted:
            if not valid:
                st.error("Complete all required fields before saving.")
            elif to_base(amount, used_unit) > to_base(current, unit) + 1e-8:
                st.error("This amount exceeds the remaining stock. Refresh the app if another user just logged usage.")
            else:
                try:
                    # Lock chemical row and recalculate within the transaction to prevent concurrent overuse.
                    with connection() as conn:
                        with conn.cursor() as cur:
                            cur.execute("SELECT starting_amount, unit FROM chemicals WHERE id=%s AND active=TRUE FOR UPDATE", (selected[0],))
                            locked = cur.fetchone()
                            if not locked:
                                raise ValueError("Chemical was archived. Refresh and try again.")
                            cur.execute("SELECT amount, unit FROM usage_logs WHERE chemical_id=%s", (selected[0],))
                            used_base = sum(to_base(a, u) for a, u in cur.fetchall())
                            available_base = to_base(locked[0], locked[1]) - used_base
                            if to_base(amount, used_unit) > available_base + 1e-8:
                                raise ValueError("Insufficient stock; another user may have logged usage.")
                            cur.execute("INSERT INTO usage_logs (chemical_id, used_on, amount, unit, note) VALUES (%s,%s,%s,%s,%s)",
                                        (selected[0], used_on, amount, used_unit, note.strip()))
                    st.success("Usage saved.")
                    st.rerun()
                except Exception as exc:
                    st.error(f"Could not save usage: {exc}")

with inventory_tab:
    st.subheader("Remaining inventory")
    show_archived = st.checkbox("Include archived chemicals", value=False)
    visible = chemicals if show_archived else active
    rows = []
    for c in visible:
        stock = remaining(c, logs)
        rows.append({"Chemical": c[1], "Identifier": c[2], "Remaining": round(stock, 4),
                     "Unit": c[4], "Starting": c[3], "Status": "Active" if c[5] else "Archived"})
    if rows:
        st.dataframe(pd.DataFrame(rows), hide_index=True, use_container_width=True)
        st.download_button("Download inventory CSV", pd.DataFrame(rows).to_csv(index=False),
                           "chemical_inventory.csv", "text/csv", use_container_width=True)
    else:
        st.info("No chemicals yet.")

with history_tab:
    st.subheader("Usage history")
    if logs:
        entries = [{"Log ID": r[0], "Chemical": r[2], "Date": r[3], "Amount": r[4], "Unit": r[5], "Used by": r[6]} for r in logs]
        df = pd.DataFrame(entries)
        st.dataframe(df, hide_index=True, use_container_width=True)
        st.download_button("Download history CSV", df.to_csv(index=False), "chemical_usage_history.csv", "text/csv", use_container_width=True)
        st.warning("Deleting a usage entry restores its amount to remaining stock.")
        with st.expander("Correct an incorrect usage entry"):
            chosen_log = st.selectbox("Entry to delete", logs, format_func=lambda r: f"#{r[0]} — {r[2]} — {r[4]} {r[5]} ({r[3]})")
            confirm = st.checkbox("I understand this permanently deletes the selected log")
            if st.button("Delete selected entry", disabled=not confirm):
                try:
                    run("DELETE FROM usage_logs WHERE id=%s", (chosen_log[0],))
                    st.rerun()
                except Exception as exc:
                    st.error(f"Could not delete entry: {exc}")
    else:
        st.info("No usage recorded yet.")

with manage_tab:
    st.subheader("Add a chemical")
    with st.form("add_chemical", clear_on_submit=True):
        name = st.text_input("Chemical name *")
        company = st.text_input("Company it's from *")
        product_number = st.text_input("Product number *", help="Enter this as text so letters and leading zeros are preserved.")
        identifier = st.text_input("Identifier (optional)", placeholder="CAS, bottle ID, or shelf label")
        starting = st.number_input("Starting amount", min_value=0.0, value=0.0, step=1.0)
        unit = st.selectbox("Stock unit", list(UNIT_GROUPS))
        st.caption("* Required. The saved chemical name will be: Chemical name - Company - Product number")
        add = st.form_submit_button("Add chemical", type="primary", use_container_width=True)
    if add:
        if not all(value.strip() for value in (name, company, product_number)):
            st.error("Chemical name, company, and product number are all required.")
        else:
            # Store all three pieces in the existing name column; no schema change.
            full_name = " - ".join((name.strip(), company.strip(), product_number.strip()))
            try:
                run("INSERT INTO chemicals (name, identifier, starting_amount, unit) VALUES (%s,%s,%s,%s)",
                    (full_name, identifier.strip(), starting, unit))
                st.rerun()
            except Exception as exc:
                st.error(f"Could not add chemical: {exc}")
    if chemicals:
        st.divider()
        st.subheader("Archive or restore")
        selected_manage = st.selectbox("Chemical to manage", chemicals, format_func=label)
        action = "Archive" if selected_manage[5] else "Restore"
        st.caption("Archiving hides a chemical from new usage logs but preserves its history.")
        if st.button(f"{action} chemical", use_container_width=True):
            try:
                run("UPDATE chemicals SET active=%s WHERE id=%s", (not selected_manage[5], selected_manage[0]))
                st.rerun()
            except Exception as exc:
                st.error(f"Could not update chemical: {exc}")

st.divider()
st.caption("Important: This starter app has no user authentication. Anyone with access to the app can edit inventory and delete usage entries. Add access control before handling sensitive lab data.")
